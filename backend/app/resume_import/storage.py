"""Private local storage for resume files.

The physical name is always a UUID generated by the server. The original file
name is only kept as metadata and is never used to build a path.

TOCTOU guarantees
-----------------
On POSIX (Linux) every critical operation (``stage``, ``commit``,
``write_extracted_text``, ``delete_key``, ``exists``, ``open_file``) pins the
storage root with ``O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC`` and
navigates component-by-component using ``dir_fd``-relative syscalls.
Publication uses ``os.link(..., follow_symlinks=False)`` followed by
``os.unlink(..., dir_fd=...)`` so that concurrent creation of a destination file
cannot be overwritten.

On Windows, ``os.open``, ``os.mkdir``, ``os.unlink``, ``os.stat``, and
``os.rename`` do not support ``dir_fd``.  Path-based pre-checks
(``_is_link_or_reparse_point``) run before operations, and ``os.rename`` is
used instead of ``os.replace`` so that an existing destination fails with
``FileExistsError`` rather than being overwritten.  However, a residual TOCTOU
window between path validation and the OS syscall remains on Windows and is
documented explicitly.
"""

from __future__ import annotations

import hmac
import os
import re
import stat
import uuid
from collections.abc import Iterator
from contextlib import contextmanager, suppress
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import BinaryIO

from app.core.config import PROJECT_ROOT, Settings, get_settings
from app.resume_import.exceptions import (
    InvalidResumeFileError,
    ResumeTooLargeError,
    StorageError,
)
from app.resume_import.hashing import CHUNK_SIZE, Sha256Accumulator

_FILE_ATTRIBUTE_REPARSE_POINT = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x0400)
_TEMP_FILENAME_RE = re.compile(r"^[0-9a-f]{32}\.part$")
_ALLOWED_UPLOAD_EXTENSIONS = (".pdf", ".docx")

# Feature detection: True only when the platform supports dir_fd for open,
# link, unlink, stat, and mkdir.
_SUPPORTS_DIR_FD = (
    os.name == "posix"
    and hasattr(os, "O_DIRECTORY")
    and hasattr(os, "O_NOFOLLOW")
    and os.open in getattr(os, "supports_dir_fd", set())
)

_SUPPORTS_LINK_DIR_FD = _SUPPORTS_DIR_FD and os.link in getattr(os, "supports_dir_fd", set())
_SUPPORTS_UNLINK_DIR_FD = _SUPPORTS_DIR_FD and os.unlink in getattr(os, "supports_dir_fd", set())
_SUPPORTS_STAT_DIR_FD = _SUPPORTS_DIR_FD and os.stat in getattr(os, "supports_dir_fd", set())
_SUPPORTS_MKDIR_DIR_FD = _SUPPORTS_DIR_FD and os.mkdir in getattr(os, "supports_dir_fd", set())
_SUPPORTS_RMDIR_DIR_FD = _SUPPORTS_DIR_FD and os.rmdir in getattr(os, "supports_dir_fd", set())
_SUPPORTS_POSIX_PINNING = (
    _SUPPORTS_DIR_FD
    and _SUPPORTS_LINK_DIR_FD
    and _SUPPORTS_UNLINK_DIR_FD
    and _SUPPORTS_STAT_DIR_FD
    and _SUPPORTS_MKDIR_DIR_FD
)


# ---------------------------------------------------------------------------
# Descriptor-relative directory handle
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class _SafeDirHandle:
    """Pinned directory descriptor (POSIX) or path-only handle (Windows)."""

    fd: int | None
    path: Path


def _dir_open_flags() -> int:
    return (
        os.O_RDONLY
        | getattr(os, "O_DIRECTORY", 0)
        | getattr(os, "O_NOFOLLOW", 0)
        | getattr(os, "O_CLOEXEC", 0)
    )


def _fsync_dir_fd(fd: int | None) -> None:
    """Best-effort directory fsync on POSIX; ignores filesystems without support."""
    if fd is None or not hasattr(os, "fsync"):
        return
    try:
        os.fsync(fd)
    except OSError:
        return


@contextmanager
def _pin_dir(directory: Path) -> Iterator[_SafeDirHandle]:
    """Open *directory* with ``O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC`` on POSIX."""
    if not _SUPPORTS_DIR_FD:
        yield _SafeDirHandle(fd=None, path=directory)
        return

    try:
        fd = os.open(directory, _dir_open_flags())
    except OSError as exc:
        raise StorageError("failed to open storage directory") from exc

    try:
        st = os.fstat(fd)
        if not stat.S_ISDIR(st.st_mode):
            raise StorageError("pinned descriptor is not a directory")
        yield _SafeDirHandle(fd=fd, path=directory)
    finally:
        os.close(fd)


@contextmanager
def _pin_child_dir(
    parent: _SafeDirHandle,
    name: str,
    *,
    create: bool = False,
) -> Iterator[_SafeDirHandle]:
    """Navigate into child directory *name* relative to *parent* (POSIX).

    If *create* is True and *name* does not exist, creates it with mode ``0o700``
    via ``os.mkdir(..., dir_fd=parent.fd)`` before opening and validating it.
    """
    if parent.fd is None:
        raise StorageError("descriptor-relative navigation requires POSIX")

    if create:
        if not _SUPPORTS_MKDIR_DIR_FD:
            raise StorageError("os.mkdir does not support dir_fd on this platform")
        try:
            os.mkdir(name, 0o700, dir_fd=parent.fd)
        except FileExistsError:
            pass
        except OSError as exc:
            raise StorageError("failed to create child storage directory") from exc

    try:
        fd = os.open(name, _dir_open_flags(), dir_fd=parent.fd)
    except OSError as exc:
        raise StorageError("failed to open child storage directory") from exc

    try:
        st = os.fstat(fd)
        if not stat.S_ISDIR(st.st_mode):
            raise StorageError("child path is not a directory")
        yield _SafeDirHandle(fd=fd, path=parent.path / name)
    finally:
        os.close(fd)


@contextmanager
def _open_pinned_dir(directory: Path) -> Iterator[int | None]:
    """Backward-compatible wrapper around ``_pin_dir`` yielding the raw fd."""
    with _pin_dir(directory) as handle:
        yield handle.fd


def _is_link_or_reparse_point(path: Path) -> bool:
    """Return True if path is a symlink, Windows junction, or reparse point."""
    try:
        if path.is_symlink():
            return True
    except OSError:
        return True

    is_junction = getattr(path, "is_junction", None)
    if callable(is_junction):
        try:
            if is_junction():
                return True
        except OSError:
            return True

    try:
        st = os.lstat(path)
    except FileNotFoundError:
        return False
    except OSError:
        return True

    if stat.S_ISLNK(st.st_mode):
        return True
    file_attrs = getattr(st, "st_file_attributes", 0)
    return bool(file_attrs & _FILE_ATTRIBUTE_REPARSE_POINT)


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class StagedUpload:
    """Temporary upload already streamed to disk, hashed and size checked.

    On POSIX ``ino`` and ``dev`` record the inode identity created by
    ``stage()`` so ``commit()`` can verify the file was not swapped.
    On Windows both are ``0``.
    """

    path: Path
    size: int
    sha256: str
    ino: int = 0
    dev: int = 0


# ---------------------------------------------------------------------------
# Main storage class
# ---------------------------------------------------------------------------
class ResumeStorage:
    """Filesystem gateway with containment checks and atomic writes."""

    def __init__(
        self,
        root: Path,
        *,
        upload_dir: str = "uploads",
        extracted_dir: str = "extracted",
        temp_dir: str = "temporary",
    ) -> None:
        self._validate_dir_name(upload_dir)
        self._validate_dir_name(extracted_dir)
        self._validate_dir_name(temp_dir)
        self._configured_root = Path(os.path.abspath(root.expanduser()))
        if _is_link_or_reparse_point(self._configured_root):
            raise StorageError("storage root cannot be a symlink or reparse point")
        if self._configured_root.exists() and not self._configured_root.is_dir():
            raise StorageError("storage root must be a directory")
        self.root = self._configured_root.resolve()
        self.upload_dir = upload_dir
        self.extracted_dir = extracted_dir
        self.temp_dir = temp_dir

    @classmethod
    def from_settings(cls, settings: Settings | None = None) -> ResumeStorage:
        current = settings or get_settings()
        root = current.storage_root
        if not root.is_absolute():
            root = PROJECT_ROOT / root
        return cls(
            root,
            upload_dir=current.resume_upload_dir,
            extracted_dir=current.resume_extracted_dir,
            temp_dir=current.resume_temp_dir,
        )

    @property
    def upload_root(self) -> Path:
        return self.root / self.upload_dir

    @property
    def extracted_root(self) -> Path:
        return self.root / self.extracted_dir

    @property
    def temp_root(self) -> Path:
        return self.root / self.temp_dir

    def ensure_ready(self) -> None:
        self._validate_root(create=True)
        if _SUPPORTS_POSIX_PINNING:
            with _pin_dir(self.root) as root_handle:
                for dirname in (self.upload_dir, self.extracted_dir, self.temp_dir):
                    with _pin_child_dir(root_handle, dirname, create=True):
                        pass
            return
        for directory in (self.upload_root, self.extracted_root, self.temp_root):
            self._validate_managed_directory(directory, create=True)

    # ------------------------------------------------------------------
    # Upload lifecycle
    # ------------------------------------------------------------------
    def stage(self, stream: BinaryIO, *, max_bytes: int) -> StagedUpload:
        """Stream an upload to a temp file, enforcing the size limit as it reads."""
        self.ensure_ready()
        temp_name = f"{uuid.uuid4().hex}.part"
        temp_path = self.temp_root / temp_name

        if _SUPPORTS_POSIX_PINNING:
            return self._stage_posix(stream, temp_name, temp_path, max_bytes=max_bytes)
        return self._stage_windows(stream, temp_name, temp_path, max_bytes=max_bytes)

    def _stage_posix(
        self,
        stream: BinaryIO,
        temp_name: str,
        temp_path: Path,
        *,
        max_bytes: int,
    ) -> StagedUpload:
        hasher = Sha256Accumulator()
        size = 0
        ino = 0
        dev = 0
        with (
            _pin_dir(self.root) as root_handle,
            _pin_child_dir(root_handle, self.temp_dir, create=True) as temp_handle,
        ):
            try:
                fd = self._open_exclusive_write(temp_path, temp_name, dir_fd=temp_handle.fd)
                try:
                    st = os.fstat(fd)
                    ino = st.st_ino
                    dev = st.st_dev
                    with os.fdopen(fd, "wb", closefd=True) as handle:
                        fd = -1
                        while True:
                            chunk = stream.read(CHUNK_SIZE)
                            if not chunk:
                                break
                            size += len(chunk)
                            if size > max_bytes:
                                raise ResumeTooLargeError("resume file exceeds the upload limit")
                            hasher.update(chunk)
                            handle.write(chunk)
                        handle.flush()
                        os.fsync(handle.fileno())
                except BaseException:
                    if fd >= 0:
                        os.close(fd)
                    raise
                if size == 0:
                    raise InvalidResumeFileError("file is empty")
                _fsync_dir_fd(temp_handle.fd)
            except (ResumeTooLargeError, InvalidResumeFileError):
                self._unlink_in_dir(temp_handle.fd, temp_name)
                raise
            except OSError as exc:
                self._unlink_in_dir(temp_handle.fd, temp_name)
                raise StorageError() from exc

        return StagedUpload(path=temp_path, size=size, sha256=hasher.hexdigest(), ino=ino, dev=dev)

    def _stage_windows(
        self,
        stream: BinaryIO,
        temp_name: str,
        temp_path: Path,
        *,
        max_bytes: int,
    ) -> StagedUpload:
        if _is_link_or_reparse_point(temp_path):
            raise StorageError("temporary target cannot be a symlink or reparse point")
        hasher = Sha256Accumulator()
        size = 0
        try:
            fd = self._open_exclusive_write(temp_path, temp_name, dir_fd=None)
            try:
                with os.fdopen(fd, "wb", closefd=True) as handle:
                    fd = -1
                    while True:
                        chunk = stream.read(CHUNK_SIZE)
                        if not chunk:
                            break
                        size += len(chunk)
                        if size > max_bytes:
                            raise ResumeTooLargeError("resume file exceeds the upload limit")
                        hasher.update(chunk)
                        handle.write(chunk)
                    handle.flush()
                    os.fsync(handle.fileno())
            except BaseException:
                if fd >= 0:
                    os.close(fd)
                raise
        except (ResumeTooLargeError, InvalidResumeFileError):
            self._unlink_if_regular(temp_path)
            raise
        except OSError as exc:
            self._unlink_if_regular(temp_path)
            raise StorageError() from exc

        if size == 0:
            self._unlink_if_regular(temp_path)
            raise InvalidResumeFileError("file is empty")

        return StagedUpload(path=temp_path, size=size, sha256=hasher.hexdigest())

    def commit(
        self,
        staged: StagedUpload,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        extension: str,
    ) -> str:
        """Atomically move a staged upload to its final private path without overwrite."""
        self.ensure_ready()
        expected_key = self.canonical_upload_key(
            profile_id=profile_id,
            document_id=document_id,
            extension=extension,
        )
        self._validate_staged_descriptor_meta(staged)

        dst_filename = f"{document_id}{extension}"
        profile_dirname = str(profile_id)

        if _SUPPORTS_POSIX_PINNING:
            self._commit_posix(staged, profile_dirname, dst_filename)
        else:
            self._commit_windows(staged, profile_dirname, dst_filename)

        return expected_key

    def _commit_posix(
        self,
        staged: StagedUpload,
        profile_dirname: str,
        dst_filename: str,
    ) -> None:
        with (
            _pin_dir(self.root) as root_handle,
            _pin_child_dir(root_handle, self.temp_dir) as temp_handle,
        ):
            self._verify_staged_identity(staged, temp_handle.fd)
            with (
                _pin_child_dir(root_handle, self.upload_dir) as upload_handle,
                _pin_child_dir(upload_handle, profile_dirname, create=True) as profile_handle,
            ):
                try:
                    os.link(
                        staged.path.name,
                        dst_filename,
                        src_dir_fd=temp_handle.fd,
                        dst_dir_fd=profile_handle.fd,
                        follow_symlinks=False,
                    )
                except OSError as exc:
                    raise StorageError("failed to publish resume upload") from exc
                _fsync_dir_fd(profile_handle.fd)

            try:
                assert temp_handle.fd is not None
                os.unlink(staged.path.name, dir_fd=temp_handle.fd)
            except OSError:
                pass

    def _commit_windows(
        self,
        staged: StagedUpload,
        profile_dirname: str,
        dst_filename: str,
    ) -> None:
        self._validate_staged_source(staged.path)
        target_dir = self.upload_root / profile_dirname
        self._validate_profile_directory(self.upload_root, target_dir)
        target = target_dir / dst_filename
        self._validate_new_target_file(target)
        try:
            self._atomic_publish_no_overwrite(staged.path, target)
        except OSError as exc:
            raise StorageError() from exc

    def discard(self, staged: StagedUpload) -> None:
        if _SUPPORTS_POSIX_PINNING:
            try:
                if staged.path.parent != self.temp_root or not _TEMP_FILENAME_RE.fullmatch(
                    staged.path.name
                ):
                    return
                with (
                    _pin_dir(self.root) as root_handle,
                    _pin_child_dir(root_handle, self.temp_dir) as temp_handle,
                ):
                    st = os.stat(staged.path.name, dir_fd=temp_handle.fd, follow_symlinks=False)
                    if stat.S_ISREG(st.st_mode):
                        assert temp_handle.fd is not None
                        os.unlink(staged.path.name, dir_fd=temp_handle.fd)
            except (OSError, StorageError):
                return
            return
        self._unlink_if_regular(staged.path)

    def write_extracted_text(
        self,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        text: str,
    ) -> str:
        """Write a UTF-8 mirror of the extracted text atomically without overwrite."""
        self.ensure_ready()
        expected_key = self.canonical_extracted_key(
            profile_id=profile_id,
            document_id=document_id,
        )

        dst_filename = f"{document_id}.txt"
        profile_dirname = str(profile_id)
        temp_name = f"{uuid.uuid4().hex}.part"
        temp_path = self.temp_root / temp_name

        if _SUPPORTS_POSIX_PINNING:
            self._write_extracted_posix(temp_name, temp_path, profile_dirname, dst_filename, text)
        else:
            self._write_extracted_windows(temp_name, temp_path, profile_dirname, dst_filename, text)

        return expected_key

    def _write_extracted_posix(
        self,
        temp_name: str,
        temp_path: Path,
        profile_dirname: str,
        dst_filename: str,
        text: str,
    ) -> None:
        with (
            _pin_dir(self.root) as root_handle,
            _pin_child_dir(root_handle, self.temp_dir) as temp_handle,
        ):
            try:
                fd = self._open_exclusive_write(temp_path, temp_name, dir_fd=temp_handle.fd)
                try:
                    with os.fdopen(fd, "wb", closefd=True) as handle:
                        fd = -1
                        handle.write(text.encode("utf-8"))
                        handle.flush()
                        os.fsync(handle.fileno())
                except BaseException:
                    if fd >= 0:
                        os.close(fd)
                    raise

                with (
                    _pin_child_dir(root_handle, self.extracted_dir) as extracted_handle,
                    _pin_child_dir(
                        extracted_handle, profile_dirname, create=True
                    ) as profile_handle,
                ):
                    os.link(
                        temp_name,
                        dst_filename,
                        src_dir_fd=temp_handle.fd,
                        dst_dir_fd=profile_handle.fd,
                        follow_symlinks=False,
                    )
                    _fsync_dir_fd(profile_handle.fd)

                self._unlink_in_dir(temp_handle.fd, temp_name)
            except OSError as exc:
                self._unlink_in_dir(temp_handle.fd, temp_name)
                raise StorageError() from exc
            except StorageError:
                self._unlink_in_dir(temp_handle.fd, temp_name)
                raise

    def _write_extracted_windows(
        self,
        temp_name: str,
        temp_path: Path,
        profile_dirname: str,
        dst_filename: str,
        text: str,
    ) -> None:
        target_dir = self.extracted_root / profile_dirname
        self._validate_profile_directory(self.extracted_root, target_dir)
        target = target_dir / dst_filename
        self._validate_new_target_file(target)

        if _is_link_or_reparse_point(temp_path):
            raise StorageError("temporary target cannot be a symlink or reparse point")
        try:
            fd = self._open_exclusive_write(temp_path, temp_name, dir_fd=None)
            try:
                with os.fdopen(fd, "wb", closefd=True) as handle:
                    fd = -1
                    handle.write(text.encode("utf-8"))
                    handle.flush()
                    os.fsync(handle.fileno())
            except BaseException:
                if fd >= 0:
                    os.close(fd)
                raise
            self._atomic_publish_no_overwrite(temp_path, target)
        except OSError as exc:
            self._unlink_if_regular(temp_path)
            raise StorageError() from exc

    # ------------------------------------------------------------------
    # Lookup, ownership and deletion
    # ------------------------------------------------------------------
    _MEDIA_TYPE_EXTENSIONS: dict[str, str] = {
        "application/pdf": ".pdf",
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx",
    }

    def canonical_upload_key(
        self,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        extension: str,
    ) -> str:
        if extension not in _ALLOWED_UPLOAD_EXTENSIONS:
            raise StorageError("unsupported resume file extension")
        return f"{self.upload_dir}/{profile_id}/{document_id}{extension}"

    def canonical_extracted_key(
        self,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
    ) -> str:
        return f"{self.extracted_dir}/{profile_id}/{document_id}.txt"

    def owned_upload_key(
        self,
        *,
        storage_key: str,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        media_type: str,
    ) -> str | None:
        """Return the canonical upload key only if storage_key proves ownership."""
        extension = self._MEDIA_TYPE_EXTENSIONS.get(media_type)
        if extension is None:
            return None
        expected = self.canonical_upload_key(
            profile_id=profile_id,
            document_id=document_id,
            extension=extension,
        )
        return expected if hmac.compare_digest(storage_key, expected) else None

    def owned_extracted_key(
        self,
        *,
        storage_key: str | None,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
    ) -> str | None:
        """Return the canonical extracted key only if storage_key proves ownership."""
        if not storage_key:
            return None
        expected = self.canonical_extracted_key(
            profile_id=profile_id,
            document_id=document_id,
        )
        return expected if hmac.compare_digest(storage_key, expected) else None

    def relative_key(self, path: Path) -> str:
        """Derive a storage key from *path*.

        Note: this inspects the path at the moment of the call and must not be
        relied upon as a permanent TOCTOU guarantee.  Prefer
        ``canonical_upload_key`` and ``canonical_extracted_key``.
        """
        self._validate_root(create=False)
        try:
            self._ensure_within(self.root, path)
            return path.resolve().relative_to(self.root).as_posix()
        except ValueError as exc:
            raise StorageError() from exc

    def resolve(self, storage_key: str) -> Path:
        """Resolve *storage_key* to a validated ``Path``.

        Note: the returned ``Path`` reflects the filesystem state at validation
        time and is not a permanent guarantee against later filesystem swaps.
        On POSIX, critical operations use descriptor-relative syscalls instead.
        """
        self._validate_root(create=False)
        parts = self._validate_relative_key(storage_key)
        candidate = self._assert_no_symlinks(self.root, parts)
        resolved = candidate.resolve()
        if resolved == self.root or not resolved.is_relative_to(self.root) or resolved != candidate:
            raise StorageError()
        return candidate

    @contextmanager
    def open_file(self, storage_key: str) -> Iterator[BinaryIO]:
        """Safely open a managed resume file for reading without following symlinks."""
        parts = self._validate_managed_file_key(storage_key)
        managed_dirname, profile_dirname, filename = parts

        if _SUPPORTS_POSIX_PINNING:
            with (
                _pin_dir(self.root) as root_handle,
                _pin_child_dir(root_handle, managed_dirname) as managed_handle,
                _pin_child_dir(managed_handle, profile_dirname) as profile_handle,
            ):
                flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_CLOEXEC", 0)
                try:
                    fd = os.open(filename, flags, dir_fd=profile_handle.fd)
                except OSError as exc:
                    raise StorageError("failed to open managed file") from exc
                try:
                    st = os.fstat(fd)
                    if not stat.S_ISREG(st.st_mode):
                        raise StorageError("managed target is not a regular file")
                    with os.fdopen(fd, "rb", closefd=True) as handle:
                        fd = -1
                        yield handle
                finally:
                    if fd >= 0:
                        os.close(fd)
            return

        path = self.resolve(storage_key)
        if _is_link_or_reparse_point(path):
            raise StorageError("managed target cannot be a symlink or reparse point")
        flags = os.O_RDONLY | getattr(os, "O_BINARY", 0)
        try:
            fd = os.open(path, flags)
        except OSError as exc:
            raise StorageError("failed to open managed file") from exc
        try:
            st = os.fstat(fd)
            if not stat.S_ISREG(st.st_mode):
                raise StorageError("managed target is not a regular file")
            with os.fdopen(fd, "rb", closefd=True) as handle:
                fd = -1
                yield handle
        finally:
            if fd >= 0:
                os.close(fd)

    def delete_key(self, storage_key: str) -> None:
        """Delete a managed resume file safely."""
        parts = self._validate_managed_file_key(storage_key)
        managed_dirname, profile_dirname, filename = parts

        if _SUPPORTS_POSIX_PINNING:
            self._delete_posix(managed_dirname, profile_dirname, filename)
        else:
            self._delete_windows(storage_key)

    def _delete_posix(
        self,
        managed_dirname: str,
        profile_dirname: str,
        filename: str,
    ) -> None:
        with (
            _pin_dir(self.root) as root_handle,
            _pin_child_dir(root_handle, managed_dirname) as managed_handle,
        ):
            try:
                with _pin_child_dir(managed_handle, profile_dirname) as profile_handle:
                    try:
                        st = os.stat(filename, dir_fd=profile_handle.fd, follow_symlinks=False)
                    except FileNotFoundError:
                        return
                    if stat.S_ISLNK(st.st_mode):
                        raise StorageError("refusing to delete a symbolic link in storage")
                    if not stat.S_ISREG(st.st_mode):
                        raise StorageError("cannot delete a non-regular file")
                    assert profile_handle.fd is not None
                    os.unlink(filename, dir_fd=profile_handle.fd)
            except StorageError as exc:
                if isinstance(exc.__cause__, FileNotFoundError):
                    return
                raise
            except OSError as exc:
                raise StorageError() from exc

            if _SUPPORTS_RMDIR_DIR_FD:
                with suppress(OSError):
                    os.rmdir(profile_dirname, dir_fd=managed_handle.fd)

    def _delete_windows(self, storage_key: str) -> None:
        path = self.resolve(storage_key)
        if path.exists() and path.is_dir():
            raise StorageError("cannot delete a storage directory")
        try:
            path.unlink(missing_ok=True)
            self._remove_empty_directory(path.parent)
        except OSError as exc:
            raise StorageError() from exc

    def exists(self, storage_key: str) -> bool:
        """Check whether *storage_key* points to an existing regular file."""
        try:
            parts = self._validate_relative_key(storage_key)
            if len(parts) != 3:
                return False

            if _SUPPORTS_POSIX_PINNING:
                return self._exists_posix(parts[0], parts[1], parts[2])

            return self.resolve(storage_key).is_file()
        except StorageError:
            return False

    def _exists_posix(self, managed_dirname: str, profile_dirname: str, filename: str) -> bool:
        try:
            with (
                _pin_dir(self.root) as root_handle,
                _pin_child_dir(root_handle, managed_dirname) as managed_handle,
                _pin_child_dir(managed_handle, profile_dirname) as profile_handle,
            ):
                st = os.stat(filename, dir_fd=profile_handle.fd, follow_symlinks=False)
                return stat.S_ISREG(st.st_mode)
        except (OSError, StorageError):
            return False

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------
    @staticmethod
    def _validate_dir_name(name: str) -> None:
        if (
            not name
            or name.strip() != name
            or "/" in name
            or "\\" in name
            or ":" in name
            or "\x00" in name
            or name in (".", "..")
        ):
            raise StorageError("managed directory name is invalid")

    def _validate_managed_file_key(self, storage_key: str) -> tuple[str, str, str]:
        parts = self._validate_relative_key(storage_key)
        if parts[0] not in (self.upload_dir, self.extracted_dir) or len(parts) != 3:
            raise StorageError("operation is only permitted for managed resume files")

        managed_dirname, profile_dirname, filename = parts
        try:
            parsed_profile = uuid.UUID(profile_dirname)
        except ValueError as exc:
            raise StorageError("invalid profile identifier in storage key") from exc
        if str(parsed_profile) != profile_dirname:
            raise StorageError("non-canonical profile identifier in storage key")

        if "." not in filename:
            raise StorageError("invalid filename in storage key")
        stem, dot_ext = filename.rsplit(".", 1)
        ext = f".{dot_ext}"
        try:
            parsed_doc = uuid.UUID(stem)
        except ValueError as exc:
            raise StorageError("invalid document identifier in storage key") from exc
        if str(parsed_doc) != stem:
            raise StorageError("non-canonical document identifier in storage key")

        if managed_dirname == self.upload_dir and ext not in _ALLOWED_UPLOAD_EXTENSIONS:
            raise StorageError("invalid upload extension in storage key")
        if managed_dirname == self.extracted_dir and ext != ".txt":
            raise StorageError("invalid extracted extension in storage key")

        return managed_dirname, profile_dirname, filename

    def _validate_staged_descriptor_meta(self, staged: StagedUpload) -> None:
        if staged.path.parent != self.temp_root:
            raise StorageError("staged upload must reside in temporary storage")
        if not _TEMP_FILENAME_RE.fullmatch(staged.path.name):
            raise StorageError("staged upload filename does not match internal pattern")

    def _validate_root(self, *, create: bool) -> None:
        if _is_link_or_reparse_point(self._configured_root):
            raise StorageError("storage root cannot be a symlink or reparse point")
        if self._configured_root.exists():
            if not self._configured_root.is_dir():
                raise StorageError("storage root must be a directory")
        elif create:
            try:
                self._configured_root.mkdir(parents=True, exist_ok=True)
            except OSError as exc:
                raise StorageError() from exc
            if (
                _is_link_or_reparse_point(self._configured_root)
                or not self._configured_root.is_dir()
            ):
                raise StorageError("storage root failed post-creation integrity check")
        if self._configured_root.exists() and self._configured_root.resolve() != self.root:
            raise StorageError("storage root resolved outside expected location")

    def _validate_managed_directory(self, directory: Path, *, create: bool) -> None:
        if _is_link_or_reparse_point(directory):
            raise StorageError("storage directory cannot be a symlink or reparse point")
        if directory.exists():
            if not directory.is_dir():
                raise StorageError("storage directory path is occupied by a non-directory")
        elif create:
            try:
                directory.mkdir(exist_ok=True)
            except OSError as exc:
                raise StorageError() from exc
        if _is_link_or_reparse_point(directory) or not directory.is_dir():
            raise StorageError("storage directory failed integrity verification")
        resolved = directory.resolve()
        if resolved != directory or resolved.parent != self.root:
            raise StorageError("storage directory escaped storage root")

    def _validate_profile_directory(self, parent_root: Path, profile_dir: Path) -> None:
        if _is_link_or_reparse_point(profile_dir):
            raise StorageError("profile storage directory cannot be a symlink or reparse point")
        if profile_dir.exists():
            if not profile_dir.is_dir():
                raise StorageError("profile storage path is not a directory")
        else:
            try:
                profile_dir.mkdir(exist_ok=True)
            except OSError as exc:
                raise StorageError() from exc
        if _is_link_or_reparse_point(profile_dir) or not profile_dir.is_dir():
            raise StorageError("profile storage directory failed integrity check")
        resolved = profile_dir.resolve()
        if resolved != profile_dir or resolved.parent != parent_root:
            raise StorageError("profile storage directory escaped managed root")

    def _validate_staged_source(self, staged_path: Path) -> None:
        if _is_link_or_reparse_point(staged_path):
            raise StorageError("staged upload cannot be a symlink or reparse point")
        if staged_path.parent != self.temp_root:
            raise StorageError("staged upload must reside in temporary storage")
        resolved = staged_path.resolve()
        if resolved != staged_path or resolved.parent != self.temp_root:
            raise StorageError("staged upload escaped temporary storage")
        if not staged_path.is_file():
            raise StorageError("staged upload file is missing")

    @staticmethod
    def _validate_new_target_file(target: Path) -> None:
        if _is_link_or_reparse_point(target):
            raise StorageError("target path cannot be a symlink or reparse point")
        if target.exists():
            raise StorageError("target resume file already exists")

    @staticmethod
    def _verify_staged_identity(staged: StagedUpload, temp_fd: int | None) -> None:
        if temp_fd is None:
            return
        try:
            st = os.stat(staged.path.name, dir_fd=temp_fd, follow_symlinks=False)
        except FileNotFoundError as exc:
            raise StorageError("staged upload file has been removed") from exc
        if not stat.S_ISREG(st.st_mode):
            raise StorageError("staged upload is not a regular file")
        if (staged.ino != 0 or staged.dev != 0) and (
            st.st_ino != staged.ino or st.st_dev != staged.dev
        ):
            raise StorageError("staged upload file identity mismatch")
        if staged.size > 0 and st.st_size != staged.size:
            raise StorageError("staged upload size mismatch")

    @staticmethod
    def _open_exclusive_write(path: Path, filename: str, *, dir_fd: int | None) -> int:
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        if hasattr(os, "O_BINARY"):
            flags |= os.O_BINARY
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        if hasattr(os, "O_CLOEXEC"):
            flags |= getattr(os, "O_CLOEXEC", 0)
        if dir_fd is not None:
            return os.open(filename, flags, 0o600, dir_fd=dir_fd)
        return os.open(path, flags, 0o600)

    @staticmethod
    def _atomic_publish_no_overwrite(source: Path, target: Path) -> None:
        """Publish *source* to *target* without overwriting an existing destination.

        On Windows, ``os.rename`` (``MoveFileW`` without
        ``MOVEFILE_REPLACE_EXISTING``) fails atomically with
        ``FileExistsError`` if *target* already exists.
        """
        if _is_link_or_reparse_point(source) or _is_link_or_reparse_point(target):
            raise StorageError("cannot publish across symlinks or reparse points")
        if os.name == "nt":
            os.rename(source, target)
            return
        raise StorageError("non-POSIX path-based publish requires explicit no-overwrite support")

    @staticmethod
    def _atomic_replace(source: Path, target: Path) -> None:
        """Deprecated internal helper kept only for backward compatibility in tests."""
        if _is_link_or_reparse_point(source) or _is_link_or_reparse_point(target):
            raise StorageError("cannot replace across symlinks or reparse points")
        if _SUPPORTS_DIR_FD:
            with (
                _open_pinned_dir(source.parent) as src_fd,
                _open_pinned_dir(target.parent) as dst_fd,
            ):
                os.replace(source.name, target.name, src_dir_fd=src_fd, dst_dir_fd=dst_fd)
            return
        os.replace(source, target)

    @staticmethod
    def _unlink_in_dir(dir_fd: int | None, filename: str) -> None:
        if dir_fd is None:
            return
        try:
            os.unlink(filename, dir_fd=dir_fd)
        except OSError:
            return

    @staticmethod
    def _unlink_if_regular(path: Path) -> None:
        if _is_link_or_reparse_point(path):
            return
        try:
            path.unlink(missing_ok=True)
        except OSError:
            return

    @staticmethod
    def _validate_relative_key(storage_key: str) -> tuple[str, ...]:
        if not isinstance(storage_key, str) or not storage_key:
            raise StorageError("storage key must not be empty")
        if storage_key.strip() != storage_key:
            raise StorageError("storage key must not contain surrounding whitespace")
        if "\x00" in storage_key or "\\" in storage_key or ":" in storage_key:
            raise StorageError("storage key contains forbidden characters")
        if storage_key.startswith("/") or storage_key.endswith("/"):
            raise StorageError("storage key must be a relative path")
        if PurePosixPath(storage_key).is_absolute() or Path(storage_key).is_absolute():
            raise StorageError("storage key must be relative")
        parts = storage_key.split("/")
        if any(part in ("", ".", "..") for part in parts):
            raise StorageError("storage key contains invalid path segments")
        return tuple(parts)

    @staticmethod
    def _assert_no_symlinks(base: Path, parts: tuple[str, ...]) -> Path:
        current = base
        for part in parts:
            current = current / part
            if _is_link_or_reparse_point(current):
                raise StorageError("symbolic links are not permitted in storage")
        return current

    @classmethod
    def _ensure_within(cls, root: Path, path: Path) -> None:
        if _is_link_or_reparse_point(root) or _is_link_or_reparse_point(path):
            raise StorageError("symbolic links are not permitted in storage")
        lex_root = Path(os.path.abspath(root))
        lex_path = Path(os.path.abspath(path))
        if lex_path == lex_root or not lex_path.is_relative_to(lex_root):
            raise StorageError()
        rel_parts = lex_path.relative_to(lex_root).parts
        if rel_parts:
            cls._assert_no_symlinks(lex_root, rel_parts)
        resolved_root = root.resolve()
        resolved = path.resolve()
        if resolved == resolved_root or not resolved.is_relative_to(resolved_root):
            raise StorageError()

    def _remove_empty_directory(self, directory: Path) -> None:
        if _is_link_or_reparse_point(directory):
            return
        if directory.parent not in (self.upload_root, self.extracted_root):
            return
        try:
            directory.rmdir()
        except OSError:
            return
