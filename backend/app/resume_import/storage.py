"""Private local storage for resume files.

The physical name is always a UUID generated by the server. The original file
name is only kept as metadata and is never used to build a path.
"""

from __future__ import annotations

import hmac
import os
import uuid
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import BinaryIO

from app.core.config import PROJECT_ROOT, Settings, get_settings
from app.resume_import.exceptions import (
    InvalidResumeFileError,
    ResumeTooLargeError,
    StorageError,
)
from app.resume_import.hashing import CHUNK_SIZE, Sha256Accumulator


@dataclass(frozen=True)
class StagedUpload:
    """Temporary upload already streamed to disk, hashed and size checked."""

    path: Path
    size: int
    sha256: str


class ResumeStorage:
    """Filesystem gateway with containment checks and atomic writes."""

    def __init__(
        self,
        root: Path,
        *,
        upload_dir: str = "uploads",
        extracted_dir: str = "extracted",
        temp_dir: str = "temporary",
    ) -> None:
        self.root = root.expanduser().resolve()
        self.upload_dir = upload_dir
        self.extracted_dir = extracted_dir
        self.temp_dir = temp_dir

    @classmethod
    def from_settings(cls, settings: Settings | None = None) -> ResumeStorage:
        current = settings or get_settings()
        root = current.storage_root
        if not root.is_absolute():
            root = PROJECT_ROOT / root
        return cls(
            root,
            upload_dir=current.resume_upload_dir,
            extracted_dir=current.resume_extracted_dir,
            temp_dir=current.resume_temp_dir,
        )

    @property
    def upload_root(self) -> Path:
        return self.root / self.upload_dir

    @property
    def extracted_root(self) -> Path:
        return self.root / self.extracted_dir

    @property
    def temp_root(self) -> Path:
        return self.root / self.temp_dir

    def ensure_ready(self) -> None:
        try:
            for directory in (self.upload_root, self.extracted_root, self.temp_root):
                directory.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise StorageError() from exc

    # ------------------------------------------------------------------
    # Upload lifecycle
    # ------------------------------------------------------------------
    def stage(self, stream: BinaryIO, *, max_bytes: int) -> StagedUpload:
        """Stream an upload to a temp file, enforcing the size limit as it reads."""
        self.ensure_ready()
        temp_path = self.temp_root / f"{uuid.uuid4().hex}.part"
        hasher = Sha256Accumulator()
        size = 0
        try:
            with temp_path.open("xb") as handle:
                while True:
                    chunk = stream.read(CHUNK_SIZE)
                    if not chunk:
                        break
                    size += len(chunk)
                    if size > max_bytes:
                        raise ResumeTooLargeError("resume file exceeds the upload limit")
                    hasher.update(chunk)
                    handle.write(chunk)
                handle.flush()
                os.fsync(handle.fileno())
        except (ResumeTooLargeError, InvalidResumeFileError):
            temp_path.unlink(missing_ok=True)
            raise
        except OSError as exc:
            temp_path.unlink(missing_ok=True)
            raise StorageError() from exc

        if size == 0:
            temp_path.unlink(missing_ok=True)
            raise InvalidResumeFileError("file is empty")

        return StagedUpload(path=temp_path, size=size, sha256=hasher.hexdigest())

    def commit(
        self,
        staged: StagedUpload,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        extension: str,
    ) -> str:
        """Atomically move a staged upload to its final private path."""
        target_dir = self.upload_root / str(profile_id)
        target = target_dir / f"{document_id}{extension}"
        try:
            target_dir.mkdir(parents=True, exist_ok=True)
            self._ensure_within(self.upload_root, target)
            os.replace(staged.path, target)
        except OSError as exc:
            raise StorageError() from exc
        return self.relative_key(target)

    def discard(self, staged: StagedUpload) -> None:
        staged.path.unlink(missing_ok=True)

    def write_extracted_text(
        self,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        text: str,
    ) -> str:
        """Write a UTF-8 mirror of the extracted text, atomically."""
        self.ensure_ready()
        target_dir = self.extracted_root / str(profile_id)
        target = target_dir / f"{document_id}.txt"
        temp_path = self.temp_root / f"{uuid.uuid4().hex}.part"
        try:
            target_dir.mkdir(parents=True, exist_ok=True)
            self._ensure_within(self.extracted_root, target)
            with temp_path.open("xb") as handle:
                handle.write(text.encode("utf-8"))
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temp_path, target)
        except OSError as exc:
            temp_path.unlink(missing_ok=True)
            raise StorageError() from exc
        return self.relative_key(target)

    # ------------------------------------------------------------------
    # Lookup, ownership and deletion
    # ------------------------------------------------------------------
    _MEDIA_TYPE_EXTENSIONS: dict[str, str] = {
        "application/pdf": ".pdf",
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx",
    }

    def canonical_upload_key(
        self,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        extension: str,
    ) -> str:
        if extension not in (".pdf", ".docx"):
            raise StorageError("unsupported resume file extension")
        return f"{self.upload_dir}/{profile_id}/{document_id}{extension}"

    def canonical_extracted_key(
        self,
        *,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
    ) -> str:
        return f"{self.extracted_dir}/{profile_id}/{document_id}.txt"

    def owned_upload_key(
        self,
        *,
        storage_key: str,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
        media_type: str,
    ) -> str | None:
        """Return the canonical upload key only if storage_key proves ownership."""
        extension = self._MEDIA_TYPE_EXTENSIONS.get(media_type)
        if extension is None:
            return None
        expected = self.canonical_upload_key(
            profile_id=profile_id,
            document_id=document_id,
            extension=extension,
        )
        return expected if hmac.compare_digest(storage_key, expected) else None

    def owned_extracted_key(
        self,
        *,
        storage_key: str | None,
        profile_id: uuid.UUID,
        document_id: uuid.UUID,
    ) -> str | None:
        """Return the canonical extracted key only if storage_key proves ownership."""
        if not storage_key:
            return None
        expected = self.canonical_extracted_key(
            profile_id=profile_id,
            document_id=document_id,
        )
        return expected if hmac.compare_digest(storage_key, expected) else None

    def relative_key(self, path: Path) -> str:
        try:
            self._ensure_within(self.root, path)
            return path.resolve().relative_to(self.root).as_posix()
        except ValueError as exc:
            raise StorageError() from exc

    def resolve(self, storage_key: str) -> Path:
        parts = self._validate_relative_key(storage_key)
        candidate = self._assert_no_symlinks(self.root, parts)
        resolved = candidate.resolve()
        if resolved == self.root or not resolved.is_relative_to(self.root) or resolved != candidate:
            raise StorageError()
        return candidate

    def delete_key(self, storage_key: str) -> None:
        parts = self._validate_relative_key(storage_key)
        if parts[0] not in (self.upload_dir, self.extracted_dir) or len(parts) != 3:
            raise StorageError("deletion is only permitted for managed resume files")
        path = self.resolve(storage_key)
        if path.exists() and path.is_dir():
            raise StorageError("cannot delete a storage directory")
        try:
            path.unlink(missing_ok=True)
            self._remove_empty_directory(path.parent)
        except OSError as exc:
            raise StorageError() from exc

    def exists(self, storage_key: str) -> bool:
        try:
            return self.resolve(storage_key).is_file()
        except StorageError:
            return False

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------
    @staticmethod
    def _validate_relative_key(storage_key: str) -> tuple[str, ...]:
        if not isinstance(storage_key, str) or not storage_key:
            raise StorageError("storage key must not be empty")
        if storage_key.strip() != storage_key:
            raise StorageError("storage key must not contain surrounding whitespace")
        if "\x00" in storage_key or "\\" in storage_key or ":" in storage_key:
            raise StorageError("storage key contains forbidden characters")
        if storage_key.startswith("/") or storage_key.endswith("/"):
            raise StorageError("storage key must be a relative path")
        if PurePosixPath(storage_key).is_absolute() or Path(storage_key).is_absolute():
            raise StorageError("storage key must be relative")
        parts = storage_key.split("/")
        if any(part in ("", ".", "..") for part in parts):
            raise StorageError("storage key contains invalid path segments")
        return tuple(parts)

    @staticmethod
    def _assert_no_symlinks(base: Path, parts: tuple[str, ...]) -> Path:
        current = base
        for part in parts:
            current = current / part
            if current.is_symlink():
                raise StorageError("symbolic links are not permitted in storage")
        return current

    @classmethod
    def _ensure_within(cls, root: Path, path: Path) -> None:
        resolved_root = root.resolve()
        if path.is_symlink():
            raise StorageError("symbolic links are not permitted in storage")
        if path.is_relative_to(resolved_root):
            rel_parts = path.relative_to(resolved_root).parts
            if rel_parts:
                cls._assert_no_symlinks(resolved_root, rel_parts)
        resolved = path.resolve()
        if resolved == resolved_root or not resolved.is_relative_to(resolved_root):
            raise StorageError()

    def _remove_empty_directory(self, directory: Path) -> None:
        if directory.is_symlink():
            return
        if directory.parent not in (self.upload_root, self.extracted_root):
            return
        try:
            directory.rmdir()
        except OSError:
            return
